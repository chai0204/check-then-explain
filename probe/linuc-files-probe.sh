#!/bin/bash
# LinuC 主題1.02（ファイル・ディレクトリの操作と管理）の本文に載せる全コマンドを、檻の中で実際に通す。
# ここに出ない出力は本文に書かない（憲章 §3）。
#
# 実行の仕方（読者の画面と1文字ずつ揃えるための条件。どれも実測で決めた 2026-10-13）:
#   - 読者と同じ起動オプション（--hostname linuc・作業/進捗の名前付きボリューム）で作ったコンテナで、
#     このスクリプトを **PID 1 の bash** として流す（docker create → docker cp → docker start -a）。
#     docker exec で流すと umask が 0000 になり、作ったファイルが全部 666 になる（読者は 0022）。
#   - 読者は端末つきの対話シェルで打つ。結果が端末の有無で変わるものだけ、次の3つで再現する。
#       T   … 端末につないで実行し、1秒後に答えを打つ（rm や cp -i の確認）
#       I   … 対話シェル（~/.bashrc を読む）で実行する（alias・type・シェル自身のエラー文）
#       TI  … 端末つきの対話シェルで実行する（ls の横並び。読者の ls は ls --color=auto の alias で、
#             色を付けるために各ファイルを stat するので、x の無いディレクトリでは出力が変わる。
#             レビューで指摘されて実測し直した 2026-10-13）。色のエスケープ列だけを取り除いて記録する
#   - 複数の項目を出す find は sort を通す。find と tar はディレクトリを読んだ順に出し、
#     その順はファイルシステムごとに違う（ext4 は名前のハッシュ順）。ls だけは自分で並べる。
#   - 読者の docker run -it は端末を割り当てるので TERM=xterm になり、~/.bashrc の dircolors が
#     LS_COLORS を設定して ls に色が付く。記録用のコンテナは端末なしで作るので TERM=dumb になり、
#     色が付かない（実測 2026-10-13）。読者と同じ値をここで入れる。
set -u
export TERM=xterm
R() { printf '\n$ %s\n' "$*"; eval "$@" 2>&1; }
# T 答え 命令 … 端末つきで実行。答えが要らない命令は答えに - を渡す
T() { local ans=$1; shift; printf '\n$ %s\n' "$*"
      if [ "$ans" = - ]; then script -qec "$*" /dev/null < /dev/null | tr -d '\r'
      else (sleep 1; printf '%s\n' "$ans") | script -qec "$*" /dev/null | tr -d '\r'; fi; }
I() { printf '\n$ %s\n' "$*"
      bash -ic "$*" 2>&1 | grep -v -e '^bash: cannot set terminal process group' -e '^bash: no job control in this shell'; }
TI() { printf '\n$ %s\n' "$*"
       script -qec "bash -ic $(printf '%q' "$*")" /dev/null < /dev/null | tr -d '\r' | sed -e 's/\x1b\[[0-9;]*[mK]//g'; }
S() { printf '\n\n========== %s ==========\n' "$*"; }
cd ~

